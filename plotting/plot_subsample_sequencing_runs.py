# Functions for plotting cumulative contig length four-panel figures.
def plot_cumulative_contig_four_panel(
    subsample_log: str,
    true_log: str,
    outdir: str,
    data_dir: str,
    max_tsv_points_per_curve: int,
    color_map_by_type: Dict[str, Sequence[str]],
) -> None:
    specs = _curve_specs()
    true_samples = [s["sample"] for s in specs if s["log_kind"] == "true"]
    subsamples = [s["sample"] for s in specs if s["log_kind"] == "subsample"]

    rows = {}
    rows.update(_parse_curve_rows(true_log, true_samples))
    rows.update(_parse_curve_rows(subsample_log, subsamples))

    tsv_path = _write_cumulative_curve_tsv(rows, specs, data_dir, max_tsv_points_per_curve)
    print(f"Saved TSV: {tsv_path}")

    if not rows:
        print("No cumulative contig data found for S1/subsamples. Skipping four-panel plot.")
        return

    metaspades_ref_mb = None
    metaspades_ref_row = rows.get(("S1", "metaspades"))
    if metaspades_ref_row and metaspades_ref_row.get("cumulative_mbp"):
        metaspades_ref_mb = float(metaspades_ref_row["cumulative_mbp"][-1])

    pane_order = ["flye", "metamdbg", "metaspades_hybrid", "opera_ms"]
    palette_seed = ["idbaud", "megahit", "metaspades", "flye", "metamdbg", "metaspades_hybrid", "opera_ms"]
    assembler_palette = build_assembler_color_map(palette_seed, color_map_by_type=color_map_by_type)
    ordered_specs = sorted(specs, key=lambda s: float(s.get("fraction", "0")), reverse=True)
    fig, axes = plt.subplots(2, 2, figsize=(17, 12))
    axes = axes.flatten()

    for ax, assembler in zip(axes, pane_order):
        plotted = 0
        for spec in ordered_specs:
            key = (spec["sample"], assembler)
            row = rows.get(key)
            if row is None:
                continue

            fraction = float(spec.get("fraction", "0"))

            base_color = assembler_palette.get(assembler, "#4c72b0")
            # Lower subsample fractions are lighter; full fraction is darkest for that assembler hue.
            lighten_amount = 0.92 - (0.87 * max(0.0, min(1.0, fraction)))
            color = _blend_with_white(base_color, lighten_amount)
            lw = 2.6 if fraction >= 0.999 else 1.6

            x_vals = pd.concat(
                [pd.Series([0.0]), pd.Series(row["contig_count"], dtype=float)],
                ignore_index=True,
            )
            y_vals = pd.concat(
                [pd.Series([0.0]), pd.Series(row["cumulative_mbp"], dtype=float)],
                ignore_index=True,
            )

            ax.plot(x_vals, y_vals, label=spec["label"], color=color, linewidth=lw)
            ax.scatter(row["contig_count"], row["cumulative_mbp"], color=color, s=6, zorder=4)
            plotted += 1

        if plotted == 0:
            ax.set_title(f"{assembler} (no data)")
            ax.axis("off")
            continue

        ax.set_title(ASSEMBLER_LABEL_ALIASES.get(assembler, assembler))
        ax.set_xlabel("Contig count (longest to shortest, log scale)")
        ax.set_ylabel("Cumulative Contig Length (Mb, raw)")
        ax.set_xscale("log")
        ax.xaxis.set_major_formatter(mticker.FuncFormatter(lambda v, _: f"{int(v):,}" if v >= 1 else f"{v:.2g}"))
        ax.yaxis.set_major_formatter(mticker.FuncFormatter(lambda v, _: f"{v:,.0f} Mb"))

        if metaspades_ref_mb is not None:
            ax.axhline(
                metaspades_ref_mb,
                color=assembler_palette.get("metaspades", "#238B45"),
                linewidth=2,
                linestyle="-",
                label="S1 metaSPAdes total",
            )

        ax.legend(title="Subsample level", fontsize=7, title_fontsize=8, loc="best")

    fig.suptitle("Subsampling Rarefaction for Hybrid and Long Assemblers", y=1.02)
    fig.tight_layout()
    outpath = os.path.join(outdir, "subsample_s1_cumulative_contig_length_four_panel.png")
    fig.savefig(outpath, dpi=300, bbox_inches="tight")
    plt.close(fig)
    print(f"Saved: {outpath}")

# Functions for extracting subsample indices and classifying read groups.
def extract_subsample_index(sample_name: str) -> float:
    # Supports both styles:
    # - S1_subsample_1 .. S1_subsample_11
    # - S1 .. S12
    match = re.search(r"_subsample_(\d+)$", str(sample_name))
    if match:
        return float(match.group(1))

    plain = re.match(r"^S(\d+)$", str(sample_name))
    if plain:
        return float(plain.group(1))

    return float("nan")

# Functions for extracting subsample indices and classifying read groups.
def classify_read_group(path: str) -> str:
    lower = os.path.basename(str(path)).lower()
    if "long" in lower:
        return "long"
    if "r1" in lower:
        return "short_r1"
    if "r2" in lower:
        return "short_r2"
    if lower.endswith(".bam"):
        return "bam"
    return "other"


def load_input(path: str) -> pd.DataFrame:
    df = pd.read_csv(path, sep="\t")
    required = {"sample", "platform", "reads", "total_bases", "total_gbp", "status", "input"}
    missing = required - set(df.columns)
    if missing:
        raise SystemExit(f"Missing required columns: {sorted(missing)}")

    df = df[df["status"] == "ok"].copy()
    df["subsample_idx"] = df["sample"].map(extract_subsample_index)
    df = df.dropna(subset=["subsample_idx"]).copy()
    df["subsample_idx"] = df["subsample_idx"].astype(int)
    df["read_group"] = df["input"].map(classify_read_group)
    return df

# Functions for writing aggregated CSV outputs from the loaded input dataframe.
def write_outputs(df: pd.DataFrame, data_dir: str) -> Tuple[pd.DataFrame, pd.DataFrame]:
    os.makedirs(data_dir, exist_ok=True)

    platform_agg = (
        df.groupby(["sample", "subsample_idx", "platform"], as_index=False)[["reads", "total_bases", "total_gbp"]]
        .sum()
        .sort_values(["subsample_idx", "platform"])
    )

    input_agg = (
        df.groupby(["sample", "subsample_idx", "platform", "read_group"], as_index=False)[
            ["reads", "total_bases", "total_gbp"]
        ]
        .sum()
        .sort_values(["subsample_idx", "platform", "read_group"])
    )

    platform_agg.to_csv(os.path.join(data_dir, "subsample_platform_totals.csv"), index=False)
    input_agg.to_csv(os.path.join(data_dir, "subsample_input_group_totals.csv"), index=False)
    return platform_agg, input_agg

# Functions for applying plot styling and generating summary plots.
def apply_style() -> None:
    sns.set_context("notebook")
    sns.set_style("whitegrid")
    plt.rcParams.update(
        {
            "font.family": "DejaVu Sans",
            "axes.titlesize": 14,
            "axes.labelsize": 12,
            "xtick.labelsize": 10,
            "ytick.labelsize": 10,
            "legend.fontsize": 9,
            "legend.title_fontsize": 10,
        }
    )


def plot_platform_gbp(platform_agg: pd.DataFrame, outdir: str) -> None:
    plt.figure(figsize=(10, 6))
    sns.lineplot(
        data=platform_agg,
        x="subsample_idx",
        y="total_gbp",
        hue="platform",
        marker="o",
        linewidth=2,
    )
    plt.title("Total Sequencing Yield by Subsample")
    plt.xlabel("Subsample Index")
    plt.ylabel("Total Yield (Gbp)")
    plt.xticks(sorted(platform_agg["subsample_idx"].unique()))
    plt.tight_layout()
    plt.savefig(os.path.join(outdir, "subsample_yield_gbp_by_platform.png"), dpi=300)
    plt.close()

# Functions for plotting sequencing run summaries.
def plot_ont_reads(platform_agg: pd.DataFrame, outdir: str) -> None:
    ont = platform_agg[platform_agg["platform"].str.lower() == "ont"].copy()
    if ont.empty:
        return

    plt.figure(figsize=(10, 6))
    sns.lineplot(data=ont, x="subsample_idx", y="reads", marker="o", color="#2a9d8f", linewidth=2)
    plt.title("ONT Reads by Subsample")
    plt.xlabel("Subsample Index")
    plt.ylabel("Read Count")
    plt.xticks(sorted(ont["subsample_idx"].unique()))
    plt.tight_layout()
    plt.savefig(os.path.join(outdir, "subsample_ont_reads.png"), dpi=300)
    plt.close()


def plot_illumina_r1_r2(input_agg: pd.DataFrame, outdir: str) -> None:
    illumina = input_agg[input_agg["platform"].str.lower() == "illumina"].copy()
    illumina = illumina[illumina["read_group"].isin(["short_r1", "short_r2"])].copy()
    if illumina.empty:
        return

    plt.figure(figsize=(11, 6))
    sns.barplot(data=illumina, x="subsample_idx", y="total_gbp", hue="read_group", errorbar=None)
    plt.title("Illumina Yield by Subsample and Read Pair")
    plt.xlabel("Subsample Index")
    plt.ylabel("Yield (Gbp)")
    plt.tight_layout()
    plt.savefig(os.path.join(outdir, "subsample_illumina_r1_r2_gbp.png"), dpi=300)
    plt.close()

# Main function for orchestrating the loading, processing, and plotting of subsample sequencing runs.
def main() -> None:
    args = parse_args()
    os.makedirs(args.outdir, exist_ok=True)
    apply_style()

    try:
        color_map_by_type = {
            "long_read": _parse_hex_list(args.long_colors, "long_read"),
            "short_read": _parse_hex_list(args.short_colors, "short_read"),
            "hybrid_read": _parse_hex_list(args.hybrid_colors, "hybrid_read"),
        }
    except ValueError as exc:
        raise SystemExit(str(exc))

    if os.path.isfile(args.input_tsv):
        df = load_input(args.input_tsv)
        if not df.empty:
            platform_agg, input_agg = write_outputs(df, args.data_dir)
            plot_platform_gbp(platform_agg, args.outdir)
            plot_ont_reads(platform_agg, args.outdir)
            plot_illumina_r1_r2(input_agg, args.outdir)
        else:
            print("Input TSV has no rows with status=ok; skipping sequencing-run summary plots.")
    else:
        print(f"Input TSV not found: {args.input_tsv}; skipping sequencing-run summary plots.")

    plot_cumulative_contig_four_panel(
        subsample_log=args.subsample_assembly_log,
        true_log=args.true_assembly_log,
        outdir=args.outdir,
        data_dir=args.data_dir,
        max_tsv_points_per_curve=args.max_tsv_points_per_curve,
        color_map_by_type=color_map_by_type,
    )

    print(f"Saved plots to: {args.outdir}")
    print(f"Saved data tables to: {args.data_dir}")


if __name__ == "__main__":
    main()
