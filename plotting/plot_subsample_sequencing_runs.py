def _curve_specs() -> List[Dict[str, str]]:
    def _subsample_percent_label(level: int) -> str:
        # Use truncation (not rounding) so labels follow 1/12, 2/12 style expectations (8.3, 16.6, ...).
        tenths = (level * 1000) // 12
        return f"{tenths / 10.0:.1f}%"

    return [
        {"label": "100.0% (true)", "sample": "S1", "log_kind": "true", "fraction": "1.0"},
        *[
            {
                "label": _subsample_percent_label(idx),
                "sample": f"S1_subsample_{idx}",
                "log_kind": "subsample",
                "fraction": f"{idx / 12.0:.6f}",
            }
            for idx in range(1, 12)
        ],
    ]

# Downsample cumulative contig curves to a maximum number of points for plotting.
def _downsample_curve(
    contig_count: Sequence[int],
    cumulative_mbp: Sequence[float],
    max_points_per_curve: int,
) -> Tuple[List[int], List[float]]:
    if max_points_per_curve <= 0 or len(contig_count) <= max_points_per_curve:
        return list(contig_count), list(cumulative_mbp)

    n = len(contig_count)
    step = max(1, (n - 1) // (max_points_per_curve - 1))
    idxs = list(range(0, n, step))
    if idxs[-1] != n - 1:
        idxs.append(n - 1)

    return [contig_count[i] for i in idxs], [cumulative_mbp[i] for i in idxs]

# Parse curve rows from assembly summary logs for the specified samples.
def _parse_curve_rows(log_path: str, wanted_samples: Sequence[str]) -> Dict[Tuple[str, str], Dict[str, object]]:
    rows: Dict[Tuple[str, str], Dict[str, object]] = {}
    wanted = set(wanted_samples)

    for block in _split_summary_blocks(log_path):
        meta = _parse_block_meta(block)
        sample = meta.get("sample", "")
        assembler = meta.get("assembler", "")
        assembly_path = meta.get("assembly_path", "")

        if sample not in wanted:
            continue
        if not assembler or not assembly_path or not os.path.isfile(assembly_path):
            continue

        lengths = sorted(_contig_lengths_from_fasta(assembly_path), reverse=True)
        if not lengths:
            continue

        cumulative_mbp: List[float] = []
        running = 0
        for length in lengths:
            running += length
            cumulative_mbp.append(running / 1_000_000.0)

        rows[(sample, assembler)] = {
            "sample": sample,
            "assembler": assembler,
            "contig_count": list(range(1, len(lengths) + 1)),
            "cumulative_mbp": cumulative_mbp,
        }

    return rows

# Functions for parsing curve rows and writing cumulative curve TSV files. Sets dataframe records and outputs TSV for plotting.
def _write_cumulative_curve_tsv(
    rows: Dict[Tuple[str, str], Dict[str, object]],
    specs: Sequence[Dict[str, str]],
    data_dir: str,
    max_points_per_curve: int,
) -> str:
    os.makedirs(data_dir, exist_ok=True)
    label_map = {spec["sample"]: spec["label"] for spec in specs}

    records: List[Dict[str, object]] = []
    for (sample, assembler), row in rows.items():
        label = label_map.get(sample, sample)
        contig_count = row.get("contig_count", [])
        cumulative_mbp = row.get("cumulative_mbp", [])
        sampled_count, sampled_cumulative = _downsample_curve(
            contig_count=contig_count,
            cumulative_mbp=cumulative_mbp,
            max_points_per_curve=max_points_per_curve,
        )
        for cidx, cum in zip(sampled_count, sampled_cumulative):
            records.append(
                {
                    "sample": sample,
                    "label": label,
                    "assembler": assembler,
                    "contig_count": cidx,
                    "cumulative_contig_length_mb": cum,
                }
            )

    df = pd.DataFrame(records)
    outpath = os.path.join(data_dir, "s1_true_and_subsamples_cumulative_contig_lengths.tsv")
    if df.empty:
        # Keep a header-only file for reproducibility when no curves are available.
        pd.DataFrame(
            columns=[
                "sample",
                "label",
                "assembler",
                "contig_count",
                "cumulative_contig_length_mb",
            ]
        ).to_csv(outpath, sep="\t", index=False)
    else:
        df.to_csv(outpath, sep="\t", index=False)
    return outpath

