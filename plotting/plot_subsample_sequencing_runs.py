# File handling and summary block parsing functions.
def _open_text_maybe_gzip(path: str):
    if path.lower().endswith(".gz"):
        return gzip.open(path, "rt", encoding="utf-8", errors="replace")
    return open(path, "r", encoding="utf-8", errors="replace")


def _split_summary_blocks(log_path: str) -> List[str]:
    if not os.path.isfile(log_path):
        return []

    with open(log_path, "r", encoding="utf-8") as handle:
        lines = handle.readlines()

    blocks: List[str] = []
    current: List[str] = []
    for line in lines:
        if line.startswith("Timestamp:"):
            if current:
                blocks.append("".join(current))
                current = []
            current.append(line)
            continue

        if line.startswith("Assembly:") and not current:
            current.append(line)
            continue

        if current:
            current.append(line)

    if current:
        blocks.append("".join(current))
    return blocks


def _parse_block_meta(block: str) -> Dict[str, str]:
    sample = ""
    assembler = ""
    assembly_path = ""

    for line in block.splitlines():
        if line.startswith("Sample:"):
            sample = line.split("Sample:", 1)[1].strip()
        elif line.startswith("Assembler:"):
            assembler = line.split("Assembler:", 1)[1].strip()
        elif line.startswith("Assembly:"):
            assembly_path = line.split("Assembly:", 1)[1].strip()

    return {"sample": sample, "assembler": assembler, "assembly_path": assembly_path}


# Curve specification and downsampling functions. Counts contigs of length above a minimum threshold from FASTA files.
def _contig_lengths_from_fasta(path: str, min_length_bp: int = 1000) -> List[int]:
    lengths: List[int] = []
    current = 0

    with _open_text_maybe_gzip(path) as handle:
        for raw in handle:
            line = raw.strip()
            if not line:
                continue
            if line.startswith(">"):
                if current >= min_length_bp:
                    lengths.append(current)
                current = 0
                continue
            current += len(line)

    if current >= min_length_bp:
        lengths.append(current)
    return lengths

